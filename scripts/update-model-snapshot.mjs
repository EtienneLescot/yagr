#!/usr/bin/env node
/**
 * Fetches https://openrouter.ai/api/v1/models (no auth required) and generates
 * src/llm/provider-model-snapshot.ts — a static TypeScript file with context window
 * data for all major models.
 *
 * Usage: node scripts/update-model-snapshot.mjs
 * CI script: pnpm run update:snapshot
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUTPUT_FILE = path.join(ROOT, 'src/llm/provider-model-snapshot.ts');
const OPENROUTER_URL = 'https://openrouter.ai/api/v1/models';

/** Maps OpenRouter upstream prefix → internal YagrModelProvider */
const UPSTREAM_PREFIX_MAP = {
  openai: 'openai',
  anthropic: 'anthropic',
  google: 'google',
  mistralai: 'mistral',
};

function asNumber(val) {
  const n = Number(val);
  return Number.isFinite(n) && n > 0 ? n : undefined;
}

async function main() {
  console.log(`Fetching ${OPENROUTER_URL} …`);
  const res = await fetch(OPENROUTER_URL, {
    headers: { 'User-Agent': 'yagr-snapshot-updater/1.0' },
  });
  if (!res.ok) {
    throw new Error(`HTTP ${res.status} ${res.statusText} from ${OPENROUTER_URL}`);
  }

  const payload = await res.json();
  const rawModels = Array.isArray(payload.data) ? payload.data : [];
  console.log(`Received ${rawModels.length} raw models.`);

  // [provider, model, contextWindow, maxOutputTokens?]
  const entries = [];

  for (const raw of rawModels) {
    if (!raw || typeof raw !== 'object') continue;
    const id = typeof raw.id === 'string' ? raw.id.trim() : '';
    if (!id) continue;

    const slashIdx = id.indexOf('/');
    if (slashIdx === -1) continue;

    const upstreamPrefix = id.slice(0, slashIdx);
    const modelNameFromId = id.slice(slashIdx + 1);

    const contextWindow =
      asNumber(raw.context_length) ??
      asNumber(raw.top_provider?.context_length);

    if (!contextWindow) continue;

    const maxOut = asNumber(raw.top_provider?.max_completion_tokens);

    // Entry for the OpenRouter provider itself (full id as model-name)
    entries.push({ provider: 'openrouter', model: id, contextWindow, maxOutputTokens: maxOut });

    // Entry for the native upstream provider, if we support it
    const nativeProvider = UPSTREAM_PREFIX_MAP[upstreamPrefix];
    if (nativeProvider) {
      entries.push({ provider: nativeProvider, model: modelNameFromId, contextWindow, maxOutputTokens: maxOut });
    }
  }

  // De-duplicate: for each (provider, model) keep the entry with the largest context window.
  const deduped = new Map();
  for (const e of entries) {
    const key = `${e.provider}::${e.model}`;
    const existing = deduped.get(key);
    if (!existing || e.contextWindow > existing.contextWindow) {
      deduped.set(key, e);
    }
  }

  const sorted = [...deduped.values()].sort((a, b) => {
    if (a.provider !== b.provider) return a.provider.localeCompare(b.provider);
    return a.model.localeCompare(b.model);
  });

  console.log(`Writing ${sorted.length} deduplicated entries …`);

  const tuples = sorted.map(({ provider, model, contextWindow, maxOutputTokens }) => {
    const out = maxOutputTokens !== undefined ? `, ${maxOutputTokens}` : '';
    // Escape single quotes in model names (just in case)
    const safeModel = model.replace(/'/g, "\\'");
    return `  ['${provider}', '${safeModel}', ${contextWindow}${out}],`;
  });

  const output = [
    `// Auto-generated by scripts/update-model-snapshot.mjs — do not edit manually.`,
    `// Run \`pnpm run update:snapshot\` to refresh.`,
    `// Last updated: ${new Date().toISOString()} (${rawModels.length} models from ${OPENROUTER_URL})`,
    ``,
    `// [provider, model, contextWindow, maxOutputTokens?]`,
    `export type ModelSnapshotTuple = [string, string, number, number?];`,
    ``,
    `export const MODEL_SNAPSHOT: readonly ModelSnapshotTuple[] = [`,
    ...tuples,
    `];`,
    ``,
  ].join('\n');

  fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');
  console.log(`Done → ${path.relative(ROOT, OUTPUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
